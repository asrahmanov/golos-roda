import { PrismaClient } from '@prisma/client';
import bcrypt from 'bcryptjs';

const db = new PrismaClient();

async function main() {
  const email = (process.env.ADMIN_EMAIL || '').toLowerCase();
  const password = process.env.ADMIN_PASSWORD;
  if (email && password) {
    const exists = await db.user.findUnique({ where: { email } });
    if (!exists) {
      await db.user.create({ data: { email, name: 'Администратор', role: 'ADMIN', emailVerifiedAt: new Date(), passwordHash: await bcrypt.hash(password, 11) } });
      console.log(`admin created: ${email}`);
    }
  }

  if ((await db.task.count()) === 0) {
    await db.task.createMany({
      data: [
        { order: 1, icon: 'mic', hint: 'AUDIO', title: 'Расспросите старших о детстве', description: 'Позвоните или зайдите к бабушке, дедушке, родителям. Спросите: во что играли, где жили, что ели на праздники, кем мечтали стать. Запишите рассказ на диктофон прямо в кабинете.' },
        { order: 2, icon: 'camera', hint: 'PHOTO', title: 'Оцифруйте самую старую семейную фотографию', description: 'Найдите самый старый снимок в семейном альбоме, сфотографируйте его при дневном свете без бликов и загрузите. Отметьте, кто на фото, и попросите родных уточнить год и место.' },
        { order: 3, icon: 'gem', hint: 'MEMORY', title: 'Уточните историю семейной реликвии', description: 'Часы, письмо, медаль, рецепт, вышивка — у каждой вещи есть путь. Узнайте, кому она принадлежала, как попала в семью и почему её хранят.' },
        { order: 4, icon: 'mail', hint: 'MEMORY', title: 'Запишите послание потомкам', description: 'Что вы хотели бы сказать правнукам, которые откроют эту страницу через 50 лет? О чём мечтаете, что цените, какие семейные правила хотите передать.' },
      ],
    });
  }

  if ((await db.faqItem.count()) === 0) {
    await db.faqItem.createMany({
      data: [
        { order: 1, question: 'Сколько стоит участие?', answer: 'Участие в проекте и создание семейного пространства бесплатны. Фестиваль 22 ноября — тоже бесплатный, нужна только предварительная регистрация.' },
        { order: 2, question: 'Кто увидит мои фотографии и истории?', answer: 'Только те родственники, которых вы пригласите в семейное пространство. Ничего не публикуется по умолчанию. Для каждого материала можно выбрать, кто его видит. Администраторы сайта не имеют доступа к содержимому семейных архивов.' },
        { order: 3, question: 'Я не умею строить родословную. С чего начать?', answer: 'С себя! Добавьте себя, затем родителей, бабушек и дедушек — с тем, что знаете. Даты можно указывать приблизительно: «около 1930». Остальное дополнят родственники. На фестивале волонтёры помогут сделать первые шаги.' },
        { order: 4, question: 'Как пригласить родственников?', answer: 'В разделе «Участники» создайте ссылку-приглашение и отправьте её в мессенджере. Вы выбираете права: соавтор может дополнять дерево и архив, читатель — только смотреть и комментировать.' },
        { order: 5, question: 'Что взять с собой на фестиваль?', answer: 'Семейные фотографии, письма и документы — их оцифруют на месте, оригиналы останутся у вас. Приводите старшее поколение: в зоне «Голос поколений» можно записать их воспоминания.' },
        { order: 6, question: 'Можно ли выгрузить свои данные?', answer: 'Да. Хранитель пространства может в любой момент скачать ZIP-архив со всеми карточками, воспоминаниями и оригиналами файлов, а также удалить пространство целиком.' },
        { order: 7, question: 'Что будет с платформой после запуска?', answer: 'Команда «Легенда» запускает проект и передаёт его постоянному оператору — городской структуре или профильной организации — по документально согласованному плану. Сохранность данных и базовые функции — обязательное условие передачи.' },
      ],
    });
  }

  if ((await db.programItem.count()) === 0) {
    await db.programItem.createMany({
      data: [
        { order: 1, time: 'Открытие', title: 'Регистрация и открытие тематических зон', description: 'Волонтёры помогут сориентироваться и зарегистрироваться на платформе.' },
        { order: 2, time: 'Первая часть', title: 'Официальное представление проекта', zone: 'Центральная площадка', description: 'Команда «Легенда» рассказывает о миссии и планах.' },
        { order: 3, time: 'Первая часть', title: 'Демонстрация пилотной платформы', zone: 'Центральная площадка', description: 'Как построить дерево, пополнить архив и пригласить близких.' },
        { order: 4, time: 'Весь день', title: 'Мастер-классы и работа станций', description: 'Дерево, запись историй, оцифровка, консультации генеалогов.' },
        { order: 5, time: 'Вторая часть', title: 'Подведение первых результатов', zone: 'Центральная площадка', description: 'Сколько деревьев создано и историй сохранено за день.' },
        { order: 6, time: 'Финал', title: 'Церемония открытия скульптуры «Связь поколений»', zone: 'Уличная зона', description: 'При готовности объекта и наличии согласований.' },
      ],
    });
  }

  if ((await db.news.count()) === 0) {
    await db.news.create({
      data: {
        slug: 'start-proekta',
        title: 'Стартует проект «Связь поколений»',
        excerpt: 'Команда «Легенда» запускает цифровую платформу семейной памяти и готовит семейный фестиваль 22 ноября в Москве.',
        body: 'Представьте, что спустя десятилетия потомок открывает страницу своей прабабушки и не только видит фотографию, но и слышит её голос, читает воспоминания и узнаёт, где она жила, о чём мечтала и что хотела передать своей семье.\n\n«Связь поколений» помогает сделать такой опыт возможным: создать цифровую семейную летопись, которую родственники пополняют вместе.\n\n## Что уже можно сделать\n\nЗарегистрироваться, создать закрытое семейное пространство, построить дерево, добавить фотографии, документы, аудиозаписи и воспоминания, пригласить родственников.\n\n## Фестиваль\n\n22 ноября пройдёт семейный фестиваль: зоны «Моё семейное дерево», «Голос поколений», «Семейный архив», «Найди свои корни» и экспозиция «Истории, которые нас объединяют». Регистрация семей уже открыта.',
        published: true,
      },
    });
  }
}

main()
  .then(() => db.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await db.$disconnect();
    process.exit(1);
  });
